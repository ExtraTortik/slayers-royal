def test_updated_dialogues():
    with open(REPO_ROOT / "translations" / "combat_dialogues_ru.json", "r", encoding="utf-8") as f:
        cat = json.load(f)

    assert len(UPDATED_DIALOGUES) == 114, f"Expected 114 blocks, got {len(UPDATED_DIALOGUES)}"

    # Apply updated dialogues to catalog
    for b in cat["blocks"]:
        b_id = b["id"]
        assert b_id in UPDATED_DIALOGUES, f"Missing block {b_id} in UPDATED_DIALOGUES"
        lines_list = UPDATED_DIALOGUES[b_id]
        assert len(lines_list) == len(b["bubbles"]), (
            f"Block {b_id} bubble count mismatch: expected {len(b['bubbles'])}, got {len(lines_list)}"
        )
        for idx, bub in enumerate(b["bubbles"]):
            text_r = lines_list[idx]
            bub["text_ru"] = text_r
            if "\f" in text_r:
                bub["pages"] = text_r.split("\f")
            else:
                bub.pop("pages", None)

    # Validate formatting constraints
    issues = validate_dialogue_formatting(cat, max_chars_per_line=21, max_lines_per_bubble=3)
    if issues:
        print(f"Formatting issues found ({len(issues)}):")
        for iss in issues:
            print("  ", iss)

    # Validate budgets
    budget_errors = []
    for b in cat["blocks"]:
        b_id = b["id"]
        budget = b["allocated_budget_bytes"]
        enc = encode_conversation_block(b, CHARMAP)
        if len(enc) > budget:
            budget_errors.append(f"{b_id}: {len(enc)} bytes > {budget} bytes (+{len(enc) - budget})")

    if budget_errors:
        print(f"Budget errors found ({len(budget_errors)}):")
        for err in budget_errors:
            print("  ", err)

    if issues or budget_errors:
        return False

    print("ALL 114 BLOCKS PASSED VALIDATION! 100% formatted, within budget, <= 21 chars, <= 3 lines.")
    return True


def apply_to_catalog():
    catalog_path = REPO_ROOT / "translations" / "combat_dialogues_ru.json"
    with open(catalog_path, "r", encoding="utf-8") as f:
        cat = json.load(f)

    for b in cat["blocks"]:
        b_id = b["id"]
        lines_list = UPDATED_DIALOGUES[b_id]
        for idx, bub in enumerate(b["bubbles"]):
            text_r = lines_list[idx]
            bub["text_ru"] = text_r
            if "\f" in text_r:
                bub["pages"] = text_r.split("\f")
            else:
                bub.pop("pages", None)

    with open(catalog_path, "w", encoding="utf-8") as f:
        json.dump(cat, f, ensure_ascii=False, indent=2)
        f.write("\n")

    print(f"Successfully updated {catalog_path}")


