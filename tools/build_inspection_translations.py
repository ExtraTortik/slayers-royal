def wrap_inspection_string(text: str) -> str:
    """Wrap a Russian inspection string to PS1 hardware layout constraints."""
    return wrap_dialogue(
        text,
        allow_continuation=False,
        max_chars_per_line=15,
        max_lines_per_page=3,
    )


def validate_inspection_string(text: str, context: str = "") -> None:
    """Validate that a wrapped string complies with PS1 hardware layout limits."""
    if not text or not text.strip():
        raise ValueError(f"Empty inspection string for {context!r}")

    normalized = unicodedata.normalize("NFC", text)
    if text != normalized:
        raise ValueError(f"String not in NFC Unicode for {context!r}")

    lines = text.split("\n")
    if not (1 <= len(lines) <= 3):
        raise ValueError(
            f"String has {len(lines)} lines (must be 1..3) for {context!r}: {text!r}"
        )

    for i, line in enumerate(lines, 1):
        if len(line) > 15:
            raise ValueError(
                f"Line {i} has {len(line)} chars (max 15) for {context!r}: {line!r}"
            )
        for ch in line:
            if ch not in DEFAULT_CHARMAP:
                raise ValueError(
                    f"Unsupported glyph {ch!r} ({ord(ch):#06x}) in {context!r}: {line!r}"
                )


def build_inspection_translations(
    catalog_path: Path = DEFAULT_CATALOG_PATH,
    dry_run: bool = False,
    verbose: bool = True,
) -> dict[str, dict[str, Any]]:
    """Load catalog, populate Russian translations with wrapping, and save."""
    if not catalog_path.is_file():
        raise FileNotFoundError(f"Inspection catalog not found: {catalog_path}")

    catalog: dict[str, dict[str, Any]] = json.loads(
        catalog_path.read_text(encoding="utf-8")
    )

    if verbose:
        print(f"Loaded catalog with {len(catalog)} entries from {catalog_path}")

    updated_count = 0
    line_counts: dict[int, int] = {}
    max_line_len = 0

    for eng_text, entry in catalog.items():
        if eng_text not in RAW_INSPECTION_TRANSLATIONS:
            raise KeyError(f"Missing translation for key: {eng_text!r}")

        raw_ru = RAW_INSPECTION_TRANSLATIONS[eng_text]
        wrapped_ru = wrap_inspection_string(raw_ru)
        validate_inspection_string(wrapped_ru, context=eng_text)

        entry["russian"] = wrapped_ru
        updated_count += 1

        lines = wrapped_ru.split("\n")
        line_counts[len(lines)] = line_counts.get(len(lines), 0) + 1
        for line in lines:
            max_line_len = max(max_line_len, len(line))

    if verbose:
        print(f"Successfully processed {updated_count}/{len(catalog)} entries.")
        print(f"Line count distribution: {sorted(line_counts.items())}")
        print(f"Max line length across all entries: {max_line_len} (<= 15)")

    if not dry_run:
        catalog_path.write_text(
            json.dumps(catalog, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        if verbose:
            print(f"Saved updated catalog to {catalog_path}")
    else:
        if verbose:
            print("Dry run: no changes written to disk.")

    return catalog


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Populate and validate Russian room inspection translations."
    )
    parser.add_argument(
        "--catalog",
        type=Path,
        default=DEFAULT_CATALOG_PATH,
        help="Path to room_inspection_ru.json",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Validate translations without writing to file",
    )
    args = parser.parse_args()

    build_inspection_translations(
        catalog_path=args.catalog,
        dry_run=args.dry_run,
        verbose=True,
    )


if __name__ == "__main__":
    main()
