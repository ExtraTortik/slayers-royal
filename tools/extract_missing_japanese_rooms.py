def decode_jp_words(words: list[int]) -> str:
    """Decode a sequence of 16-bit words from Japanese PROG.UNT into a string."""
    chars: list[str] = []
    for w in words:
        if w == CHAR_NEWLINE:
            chars.append("\n")
        elif w in (CHAR_PAGE_CONTINUE, CHAR_STRING_TERMINATOR):
            break
        elif w in CHARMAP:
            chars.append(CHARMAP[w])
        elif 32 <= w <= 126:
            chars.append(chr(w))
        else:
            chars.append(f"<G:{w:04X}>")
    return "".join(chars)


def extract_strings_from_room_bytes(entry_bytes: bytes) -> list[str]:
    """Parse room inspection entry bytes and extract decoded Japanese strings."""
    if len(entry_bytes) < 0x0100:
        return []
    ptr_table_val = struct.unpack_from(">I", entry_bytes, 0x24)[0]
    if ptr_table_val < 0x00200000:
        return []
    ptr_table_offset = ptr_table_val - 0x00200000
    val_2c = struct.unpack_from(">I", entry_bytes, 0x2C)[0] - 0x00200000
    val_30 = struct.unpack_from(">I", entry_bytes, 0x30)[0] - 0x00200000
    ptr_table_end = min(val_2c, val_30)
    if ptr_table_end <= ptr_table_offset or (ptr_table_end - ptr_table_offset) % 4 != 0:
        return []
    num_pointers = (ptr_table_end - ptr_table_offset) // 4
    pointers = [
        struct.unpack_from(">I", entry_bytes, ptr_table_offset + i * 4)[0] - 0x00200000
        for i in range(num_pointers)
    ]
    extracted: list[str] = []
    for p_off in pointers:
        if p_off < 0 or p_off >= len(entry_bytes):
            continue
        words: list[int] = []
        curr = p_off
        while curr + 2 <= len(entry_bytes):
            w = struct.unpack_from(">H", entry_bytes, curr)[0]
            curr += 2
            words.append(w)
            if w in (CHAR_STRING_TERMINATOR, CHAR_PAGE_CONTINUE):
                break
        extracted.append(decode_jp_words(words))
    return extracted


def get_programs(
    source_bin_path: Path | None = None,
    english_prog_path: Path | None = None,
    verbose: bool = True,
) -> tuple[bytes, bytes]:
    """Load pristine source_prog and english_prog binary data."""
    bin_path = source_bin_path or DEFAULT_SOURCE_BIN
    if not bin_path.is_file():
        raise FileNotFoundError(f"Source BIN not found at {bin_path}")

    if verbose:
        print(f"Reading Japanese source PROG.UNT from {bin_path}...")
    source_prog = read_prog(bin_path, SOURCE_PROG_SHA256)

    if english_prog_path is not None and english_prog_path.is_file():
        if verbose:
            print(f"Reading English PROG.UNT directly from {english_prog_path}...")
        english_prog = english_prog_path.read_bytes()
    else:
        if verbose:
            print("Applying English base patch to derive pristine english_prog...")
        descriptor, temp_path = tempfile.mkstemp(prefix=".eng_base.", suffix=".bin")
        os.close(descriptor)
        temp_bin = Path(temp_path)
        try:
            _apply_english_base(bin_path, temp_bin)
            english_prog = read_prog(temp_bin, ENGLISH_PROG_SHA256)
        finally:
            temp_bin.unlink(missing_ok=True)

    return source_prog, english_prog


def identify_omitted_rooms(
    source_prog: bytes,
    english_prog: bytes,
    start_entry: int = 0x059,
    end_entry: int = 0x0F8,
) -> dict[str, list[str]]:
    """Scan PROG.UNT entries and find rooms with strings in Japanese but blank in English."""
    source_entries = read_unt_index(source_prog)
    english_entries = read_unt_index(english_prog)

    omitted_rooms: dict[str, list[str]] = {}
    for entry_idx in range(start_entry, min(end_entry + 1, len(source_entries))):
        s_bytes = source_entries[entry_idx].extract(source_prog)
        e_bytes = english_entries[entry_idx].extract(english_prog)

        s_strs = extract_strings_from_room_bytes(s_bytes)
        try:
            e_info = parse_inspection_entry(e_bytes, entry_index=entry_idx)
            e_strs = e_info.extracted_strings
        except Exception:
            e_strs = []

        s_active = [s for s in s_strs if s.strip()]
        e_active = [s for s in e_strs if s.strip()]

        if len(s_active) > 0 and len(e_active) == 0:
            room_hex = f"0x{entry_idx:03X}"
            omitted_rooms[room_hex] = s_strs

    return omitted_rooms


def translate_japanese_string(jp_str: str) -> str:
    """Translate a Japanese inspection string to Russian in Lina Inverse's voice."""
    if jp_str in RAW_TRANSLATIONS:
        raw_ru = RAW_TRANSLATIONS[jp_str]
    else:
        # Fallback if unknown
        raw_ru = jp_str

    # Wrap cleanly to PS1 hardware layout limits: max 15 chars/line, max 3 lines
    wrapped = wrap_dialogue(
        raw_ru,
        allow_continuation=False,
        max_chars_per_line=15,
        max_lines_per_page=3,
    )
    return unicodedata.normalize("NFC", wrapped)


def validate_room_catalog(catalog: dict[str, dict[str, Any]]) -> list[str]:
    """Validate all constraints: lines <= 3, length <= 15, valid charmap glyphs."""
    errors: list[str] = []
    for room_id, room_info in catalog.items():
        ru_strs = room_info.get("strings_ru", [])
        jp_strs = room_info.get("strings_jp", [])

        if len(ru_strs) != len(jp_strs):
            errors.append(f"{room_id}: string count mismatch (RU={len(ru_strs)}, JP={len(jp_strs)})")

        for idx, s in enumerate(ru_strs):
            if not s or not s.strip():
                errors.append(f"{room_id}[{idx}]: empty string")
                continue

            lines = s.split("\n")
            if not (1 <= len(lines) <= 3):
                errors.append(f"{room_id}[{idx}]: invalid line count {len(lines)} (must be 1..3): {s!r}")

            for line_idx, line in enumerate(lines):
                if len(line) > 15:
                    errors.append(
                        f"{room_id}[{idx}] line {line_idx}: length {len(line)} > 15 chars: {line!r}"
                    )
                for ch in line:
                    if ch not in DEFAULT_CHARMAP:
                        errors.append(
                            f"{room_id}[{idx}]: glyph {ch!r} ({ord(ch):#06x}) not in DEFAULT_CHARMAP"
                        )

    return errors


def build_missing_rooms_catalog(
    source_prog: bytes,
    english_prog: bytes,
    verbose: bool = True,
) -> dict[str, dict[str, Any]]:
    """Build the complete JSON catalog for all omitted rooms."""
    omitted = identify_omitted_rooms(source_prog, english_prog)
    if verbose:
        print(f"Identified {len(omitted)} omitted rooms in source_prog:")
        for r_id, strs in omitted.items():
            print(f"  {r_id}: {len(strs)} strings")

    catalog: dict[str, dict[str, Any]] = {}
    for r_id in sorted(omitted.keys()):
        jp_strs = omitted[r_id]
        ru_strs = [translate_japanese_string(s) for s in jp_strs]
        catalog[r_id] = {
            "strings_ru": ru_strs,
            "strings_jp": jp_strs,
        }

    return catalog


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Extract and translate omitted Japanese rooms into Russian."
    )
    parser.add_argument(
        "--source-bin",
        type=Path,
        default=DEFAULT_SOURCE_BIN,
        help="Path to original Japanese PS1 CD-ROM BIN image",
    )
    parser.add_argument(
        "--english-prog",
        type=Path,
        default=None,
        help="Optional path to extracted English PROG.UNT binary",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT_PATH,
        help="Output path for missing_rooms_jp_ru.json",
    )
    parser.add_argument(
        "--verify",
        action="store_true",
        help="Verify an existing missing_rooms_jp_ru.json without re-extracting",
    )
    parser.add_argument(
        "--quiet",
        action="store_true",
        help="Suppress verbose status messages",
    )

    args = parser.parse_args()
    verbose = not args.quiet

    if args.verify:
        if not args.output.is_file():
            print(f"Error: {args.output} does not exist for verification", file=sys.stderr)
            return 1
        data = json.loads(args.output.read_text(encoding="utf-8"))
        errors = validate_room_catalog(data)
        if errors:
            print(f"FAILED verification with {len(errors)} errors:", file=sys.stderr)
            for err in errors[:20]:
                print(f"  - {err}", file=sys.stderr)
            return 1
        if verbose:
            total_rooms = len(data)
            total_strs = sum(len(d["strings_ru"]) for d in data.values())
            print(f"SUCCESS: verified {total_rooms} rooms ({total_strs} strings), 0 errors!")
        return 0

    source_prog, english_prog = get_programs(
        source_bin_path=args.source_bin,
        english_prog_path=args.english_prog,
        verbose=verbose,
    )

    catalog = build_missing_rooms_catalog(source_prog, english_prog, verbose=verbose)

    if len(catalog) != 37:
        print(f"Warning: expected 37 omitted rooms, found {len(catalog)}", file=sys.stderr)

    if "0x059" not in catalog:
        print("Error: Lakewood MAIN ST (0x059) missing from catalog!", file=sys.stderr)
        return 1

    main_st_strs = catalog["0x059"]["strings_ru"]
    if len(main_st_strs) != 43:
        print(f"Error: 0x059 expected 43 strings, got {len(main_st_strs)}", file=sys.stderr)
        return 1

    errors = validate_room_catalog(catalog)
    if errors:
        print(f"Validation failed with {len(errors)} errors:", file=sys.stderr)
        for err in errors[:20]:
            print(f"  - {err}", file=sys.stderr)
        return 1

    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8") as f:
        json.dump(catalog, f, ensure_ascii=False, indent=2)

    total_rooms = len(catalog)
    total_strs = sum(len(d["strings_ru"]) for d in catalog.values())
    if verbose:
        print(f"Successfully extracted & translated {total_rooms} rooms ({total_strs} strings).")
        print(f"Saved catalog to {args.output} ({args.output.stat().st_size:,} bytes).")
        print("0 lines > 15 chars, 0 strings > 3 lines, 100% valid charmap glyphs.")

    return 0


if __name__ == "__main__":
    sys.exit(main())

